#!/usr/bin/env python3
"""Convert Spleen's 8x16 BDF into term's font data.

Writes user/term/src/font/spleen.rs (the glyphs docs/design.md's "The font"
takes from Spleen: printable ASCII and five ISO 8859-1 characters, each row a
binary literal) and user/term/src/font/LICENSE-spleen (the tag's LICENSE,
verbatim). The output depends only on the two input files, so running the
script again on the same tag changes nothing.

    python3 -I tools/spleen.py                       # fetch the pinned tag
    python3 -I tools/spleen.py --bdf F --license L   # from local copies

Both files must match the SHA-256 pinned below for TAG. To move to another
tag, read that tag's LICENSE first: if it is still the BSD 2-Clause licence,
update TAG, COMMIT and the two hashes, run the script and review the diff.
"""

import argparse
import hashlib
import pathlib
import re
import sys
import urllib.request

TAG = "2.3.0"
# What `git ls-remote --tags https://github.com/fcambus/spleen` gave for the
# tag on 2026-11-23 (a lightweight tag, so the commit itself).
COMMIT = "b2d04a6180d44f47396dc530f3b2ca46b87e618b"
BDF_SHA256 = "3be74111b39d48647a9a944528bd0bfaf0b926817cf85ff3746658c3f7532147"
LICENSE_SHA256 = "f33fe8679d5b2abecc4f1313ce6c6bfa58262964de5f7bca146596a7318047af"
RAW = "https://raw.githubusercontent.com/fcambus/spleen/{tag}/{file}"

# The code points the note takes from Spleen, in the font's index order.
CODE_POINTS = list(range(0x20, 0x7F)) + [0xA0, 0xA3, 0xB0, 0xB1, 0xB7]

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "user" / "term" / "src" / "font"


def fetch(name):
    url = RAW.format(tag=TAG, file=name)
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def check_hash(name, data, want):
    got = hashlib.sha256(data).hexdigest()
    if got != want:
        sys.exit(
            f"spleen: {name}: SHA-256 {got}, expected {want} for tag {TAG}; "
            "read the tag's LICENSE before pinning a new hash"
        )


def parse_bdf(text):
    """{code point: (name, 16 row bytes)} for every 8x16 glyph."""
    lines = text.splitlines()
    if "FONTBOUNDINGBOX 8 16 0 -4" not in lines:
        sys.exit("spleen: the BDF is not an 8x16 font with a descent of 4")
    glyphs = {}
    i = 0
    while i < len(lines):
        if not lines[i].startswith("STARTCHAR "):
            i += 1
            continue
        name = lines[i][len("STARTCHAR ") :].strip()
        encoding = None
        bbx = None
        rows = None
        i += 1
        while lines[i] != "ENDCHAR":
            words = lines[i].split()
            if words[0] == "ENCODING":
                encoding = int(words[1])
            elif words[0] == "BBX":
                bbx = tuple(int(w) for w in words[1:])
            elif words[0] == "BITMAP":
                rows = []
                i += 1
                while lines[i] != "ENDCHAR":
                    rows.append(int(lines[i], 16))
                    i += 1
                continue
            i += 1
        if encoding is not None and encoding >= 0:
            if bbx != (8, 16, 0, -4) or rows is None or len(rows) != 16:
                sys.exit(f"spleen: U+{encoding:04X} is not a whole 8x16 cell")
            if any(r > 0xFF for r in rows):
                sys.exit(f"spleen: U+{encoding:04X} has a row wider than 8 pixels")
            glyphs[encoding] = (name, rows)
        i += 1
    return glyphs


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def char_literal(cp):
    c = chr(cp)
    if c in "'\\":
        return f"'\\{c}'"
    if not 0x20 <= cp < 0x7F:
        return f"'\\u{{{cp:x}}}'"
    return f"'{c}'"


def render(glyphs, license_text):
    table = bytes(b for cp in CODE_POINTS for b in glyphs[cp][1])
    out = []
    w = out.append
    w("//! Spleen 8x16's glyphs for printable ASCII and five ISO 8859-1")
    w("//! characters (`docs/design.md`, \"The font\"). Generated by")
    w("//! `tools/spleen.py`: do not edit by hand, run the script again.")
    w("//!")
    w(f"//! From `spleen-8x16.bdf` of Spleen {TAG} (tag `{TAG}` of")
    w(f"//! <https://github.com/fcambus/spleen>, commit `{COMMIT[:12]}`),")
    w("//! SHA-256")
    w(f"//! `{BDF_SHA256}`.")
    w("//! Each glyph is 16 rows from the top, bit 7 the leftmost pixel.")
    w("//!")
    w("//! Spleen is released under the BSD 2-Clause licence. Its notice, from")
    w("//! that tag's `LICENSE`, copied verbatim to `LICENSE-spleen`, the file")
    w("//! the image carries as `\\licenses\\spleen.txt` on its ESP:")
    w("//!")
    w("//! ```text")
    for line in license_text.rstrip("\n").split("\n"):
        w(f"//! {line}".rstrip())
    w("//! ```")
    w("")
    w("/// FNV-1a (64-bit) of [`GLYPHS`]' rows in order, as the script computed")
    w("/// it from the BDF.")
    w(f"pub const FNV1A_64: u64 = 0x{fnv1a64(table):016X};")
    w("")
    w("/// The glyphs, in the font's index order.")
    w("#[rustfmt::skip]")
    w(f"pub const GLYPHS: [(char, [u8; 16]); {len(CODE_POINTS)}] = [")
    for cp in CODE_POINTS:
        name, rows = glyphs[cp]
        name = re.sub(r"[^A-Za-z0-9 -]", "", name)
        w(f"    // U+{cp:04X} {name}")
        w(f"    ({char_literal(cp)}, [")
        for r in rows:
            w(f"        0b{r:08b},")
        w("    ]),")
    w("];")
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--bdf", type=pathlib.Path, help="a local spleen-8x16.bdf")
    p.add_argument("--license", type=pathlib.Path, help="a local LICENSE")
    a = p.parse_args()
    bdf = a.bdf.read_bytes() if a.bdf else fetch("spleen-8x16.bdf")
    lic = a.license.read_bytes() if a.license else fetch("LICENSE")
    check_hash("spleen-8x16.bdf", bdf, BDF_SHA256)
    check_hash("LICENSE", lic, LICENSE_SHA256)
    license_text = lic.decode("utf-8")
    if "BSD" not in bdf.decode("ascii") or "Redistribution and use" not in license_text:
        sys.exit("spleen: the licence is not the one the note expects")
    glyphs = parse_bdf(bdf.decode("ascii"))
    missing = [f"U+{cp:04X}" for cp in CODE_POINTS if cp not in glyphs]
    if missing:
        sys.exit(f"spleen: the BDF lacks {', '.join(missing)}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "spleen.rs").write_text(render(glyphs, license_text))
    (OUT_DIR / "LICENSE-spleen").write_bytes(lic)
    print(f"spleen: wrote {len(CODE_POINTS)} glyphs from Spleen {TAG} to {OUT_DIR}")


if __name__ == "__main__":
    main()
